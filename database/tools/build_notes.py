"""Builds the notes of the chat from database/notes/*.md.

A note file starts with a header between two `---` lines (id, title, category, school, keywords, source) and then the Hungarian text.
Writes seed/notes.json and the repeatable migration R__notes.sql (in database/migrations and in the backend), which rewrites the table
`notes` from the files, so the files are the only place where a note is edited. Run from database/:  python tools/build_notes.py
Only the Python standard library is used."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
NOTES_DIR = HERE / "notes"
SEED_DIR = HERE / "seed"
TARGETS = [HERE / "migrations", HERE.parent / "backend" / "src" / "main" / "resources" / "db" / "migration"]
CATEGORIES = {"magic", "world"}
REQUIRED = ("id", "title", "category", "keywords", "source")
OPTIONAL = ("school",)
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def schools() -> set[str]:
    """School ids used by the stored mosaics."""
    out: set[str] = set()
    for f in SEED_DIR.glob("*.json"):
        data = json.loads(f.read_text(encoding="utf-8"))
        if isinstance(data, list):
            out.update(m["school"] for m in data if isinstance(m, dict) and "school" in m)
    return out


def parse(path: Path) -> dict:
    raw = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", raw, re.S)
    if not m:
        raise ValueError(f"{path.name}: the file must start with a header between two --- lines")
    head: dict[str, str] = {}
    for line in m.group(1).splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError(f"{path.name}: header line without a colon: {line!r}")
        head[key.strip()] = value.strip()
    unknown = set(head) - set(REQUIRED) - set(OPTIONAL)
    if unknown:
        raise ValueError(f"{path.name}: unknown header field(s): {sorted(unknown)}")
    missing = [k for k in REQUIRED if not head.get(k)]
    if missing:
        raise ValueError(f"{path.name}: missing header field(s): {missing}")
    return {
        "id": head["id"], "title": head["title"], "category": head["category"], "school": head.get("school") or None,
        "keywords": [k.strip() for k in head["keywords"].split(",") if k.strip()],
        "text": m.group(2).strip(), "source": head["source"], "file": path.name,
    }


def check(notes: list[dict]) -> list[str]:
    errors: list[str] = []
    known_schools = schools()
    seen: dict[str, str] = {}
    for n in notes:
        where = n["file"]
        if not ID_RE.match(n["id"]):
            errors.append(f"{where}: id {n['id']!r} must be lower case letters, digits and single dashes")
        if n["id"] in seen:
            errors.append(f"{where}: id {n['id']!r} is already used by {seen[n['id']]}")
        seen[n["id"]] = where
        if Path(where).stem != n["id"]:
            errors.append(f"{where}: the file name must be the id ({n['id']}.md)")
        if n["category"] not in CATEGORIES:
            errors.append(f"{where}: category {n['category']!r} is not one of {sorted(CATEGORIES)}")
        if n["school"] and n["school"] not in known_schools:
            errors.append(f"{where}: school {n['school']!r} is not a school of the stored mosaics")
        if not n["keywords"]:
            errors.append(f"{where}: at least one keyword is needed")
        if len(set(k.lower() for k in n["keywords"])) != len(n["keywords"]):
            errors.append(f"{where}: duplicate keyword")
        if not n["text"]:
            errors.append(f"{where}: the text is empty")
    return errors


def quote(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def migration(notes: list[dict]) -> str:
    lines = [
        "-- R__notes: repeatable migration generated by database/tools/build_notes.py from database/notes/*.md; do not edit by hand.",
        "-- It rewrites the table `notes` from the files: new and changed notes are written, notes without a file are removed.",
    ]
    for n in notes:
        keywords = ", ".join(n["keywords"])
        school = quote(n["school"]) if n["school"] else "NULL"
        lines.append(
            "INSERT INTO notes (id, title, category, school, keywords, text, source) VALUES "
            f"({quote(n['id'])}, {quote(n['title'])}, {quote(n['category'])}, {school}, {quote(keywords)}, {quote(n['text'])}, {quote(n['source'])})\n"
            "ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, category = EXCLUDED.category, school = EXCLUDED.school, "
            "keywords = EXCLUDED.keywords, text = EXCLUDED.text, source = EXCLUDED.source;")
    ids = ", ".join(quote(n["id"]) for n in notes)
    lines.append(f"DELETE FROM notes WHERE id NOT IN ({ids});" if notes else "DELETE FROM notes;")
    return "\n".join(lines) + "\n"


def main() -> int:
    notes = [parse(p) for p in sorted(NOTES_DIR.glob("*.md"))]
    errors = check(notes)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    (SEED_DIR / "notes.json").write_text(
        json.dumps([{k: v for k, v in n.items() if k != "file"} for n in notes], ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    sql = migration(notes)
    for target in TARGETS:
        (target / "R__notes.sql").write_text(sql, encoding="utf-8")
    print(f"written {len(notes)} note(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
